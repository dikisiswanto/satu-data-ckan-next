#!/usr/bin/env python3
"""Install pinned Portal Satu Data extension assets into the official CKAN build."""
from pathlib import Path
import re
import shutil
import sys

project_root = Path(sys.argv[1]).resolve()
upstream = Path(sys.argv[2]).resolve()
ckan_dir = upstream / "ckan"
dockerfile = ckan_dir / "Dockerfile"
if not dockerfile.is_file():
    raise SystemExit(f"CKAN Dockerfile not found: {dockerfile}")

copies = {
    project_root / "deploy/ckan/extensions/requirements.txt": ckan_dir / "extensions/requirements.txt",
    project_root / "deploy/ckan/theme/ckanext/wajo_theme/schemas/dataset.yaml": ckan_dir / "schemas/dataset.yaml",
    project_root / "deploy/ckan/initialize-extensions.sh": ckan_dir / "docker-entrypoint.d/50-portal-extensions.sh",
    project_root / "deploy/ckan/install-pages.py": ckan_dir / "install-pages.py",
    project_root / "deploy/ckan/compile-id-translations.py": ckan_dir / "compile-id-translations.py",
}
for source, destination in copies.items():
    if not source.is_file():
        raise SystemExit(f"Required extension asset is missing: {source}")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_bytes(source.read_bytes())
    if destination.suffix == ".sh":
        destination.chmod(0o755)

# Mirror the maintained local theme into the upstream CKAN build context. This
# keeps upstream code pristine while making the theme part of the versioned image.
theme_source = project_root / "deploy/ckan/theme"
theme_destination = ckan_dir / "theme"
if not (theme_source / "setup.py").is_file():
    raise SystemExit(f"Custom CKAN theme package is missing: {theme_source / 'setup.py'}")
if theme_destination.exists():
    shutil.rmtree(theme_destination)
shutil.copytree(theme_source, theme_destination)

text = dockerfile.read_text()
marker = "# Portal Satu Data CKAN extensions (generated by configure-upstream-extensions.py)"
block = f'''{marker}
COPY --chown=ckan:ckan extensions/requirements.txt /tmp/portal-ckan-extensions.txt
# Scheming schema is installed as package data and loaded via ckanext.wajo_theme:schemas/dataset.yaml.
COPY --chown=ckan:ckan docker-entrypoint.d/50-portal-extensions.sh /docker-entrypoint.d/50-portal-extensions.sh
COPY --chown=ckan:ckan theme/ /tmp/portal-ckan-theme/
COPY --chown=ckan:ckan install-pages.py /tmp/portal-install-pages.py
COPY --chown=ckan:ckan compile-id-translations.py /tmp/portal-compile-id-translations.py
# Install standard extensions and Wajo theme, then build ckanext-pages from
# its pinned upstream source with missing wheel package-data restored.
USER root
RUN python -m pip install --no-cache-dir -r /tmp/portal-ckan-extensions.txt /tmp/portal-ckan-theme \
    && python /tmp/portal-install-pages.py \
    && python /tmp/portal-compile-id-translations.py /tmp/portal-ckan-theme/ckanext/wajo_theme/i18n/id/LC_MESSAGES/ckan.po "$(python -c 'import ckan; from pathlib import Path; print(Path(ckan.__file__).resolve().parent / "i18n")')" "$(python -c 'import importlib.util; from pathlib import Path; spec = importlib.util.find_spec("ckanext.wajo_theme"); print(Path(next(iter(spec.submodule_search_locations))) / "i18n")')" \
    && rm -f /tmp/portal-ckan-extensions.txt /tmp/portal-install-pages.py /tmp/portal-compile-id-translations.py \
    && rm -rf /tmp/portal-ckan-theme
# The upstream start_ckan.sh reads EXTRA_UWSGI_OPTS without a nounset-safe fallback.
# Define an empty default; an explicit runtime environment may still override it.
ENV EXTRA_UWSGI_OPTS=""

'''
if marker in text:
    # Replace our own previous block so rerunning bootstrap updates the extension pins.
    start = text.index(marker)
    after_marker = text[start:]
    next_user = re.search(r'^USER\s+ckan(?:\s|$)', after_marker, flags=re.M)
    if not next_user:
        raise SystemExit("Could not find the USER ckan boundary after the generated extension block.")
    text = text[:start] + block + after_marker[next_user.start():]
else:
    # Install extensions before the original runtime USER ckan boundary.
    matches = list(re.finditer(r'^USER\s+ckan(?:\s|$)', text, flags=re.M))
    if not matches:
        raise SystemExit("Could not find 'USER ckan' in upstream Dockerfile; refusing unsafe injection.")
    pos = matches[0].start()
    text = text[:pos] + block + text[pos:]
dockerfile.write_text(text)

print("Installed pinned CKAN extensions, Scheming schema, Pages migration and the Wajo admin theme into the CKAN build context.")
