#!/usr/bin/env python3
"""Regression test for the generated CKAN Dockerfile overlay (no Docker needed)."""
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
CONFIGURE = ROOT / "deploy/ckan/configure-upstream-extensions.py"
MARKER = "# Portal Satu Data CKAN extensions (generated by configure-upstream-extensions.py)"


def main() -> None:
    with tempfile.TemporaryDirectory(prefix="portal-ckan-overlay-") as tmp:
        upstream = Path(tmp)
        ckan = upstream / "ckan"
        ckan.mkdir()
        dockerfile = ckan / "Dockerfile"
        dockerfile.write_text(
            "FROM ckan/ckan-base:2.12.1\n"
            "USER root\n"
            "COPY docker-entrypoint.d/* /docker-entrypoint.d/\n"
            "RUN echo build\n"
            "USER ckan\n"
            "CMD [\"/docker-entrypoint.sh\"]\n"
        )

        for _ in range(2):
            subprocess.run(
                ["python3", str(CONFIGURE), str(ROOT), str(upstream)],
                check=True,
                capture_output=True,
                text=True,
            )

        result = dockerfile.read_text()
        assert result.count(MARKER) == 1, "generated Dockerfile block must be idempotent"
        assert result.count("COPY --chown=ckan:ckan extensions/requirements.txt") == 1
        assert result.count("RUN pip install --no-cache-dir -r /tmp/portal-ckan-extensions.txt") == 1
        assert result.count("USER ckan") == 1, "the original CKAN runtime user boundary must be preserved"
        assert "ckanext-scheming==3.1.0" in (ckan / "extensions/requirements.txt").read_text()
        assert "ckanext-pages==0.5.2" in (ckan / "extensions/requirements.txt").read_text()
        assert "ckanext-dcat==2.4.4" in (ckan / "extensions/requirements.txt").read_text()
        assert "ckanext-xloader==2.5.2" in (ckan / "extensions/requirements.txt").read_text()
        assert "ckanext-geoview==0.3.2" in (ckan / "extensions/requirements.txt").read_text()
        assert "ckanext-harvest==1.6.3" in (ckan / "extensions/requirements.txt").read_text()
        assert (ckan / "schemas/dataset.yaml").is_file()
        assert "2.12.1" in result, "generated Dockerfile should use the patch-pinned official base image"
        init_script = ckan / "docker-entrypoint.d/50-portal-extensions.sh"
        assert init_script.is_file() and init_script.stat().st_mode & 0o111

    print("CKAN Docker overlay passes idempotency and required-extension smoke checks.")


if __name__ == "__main__":
    main()
