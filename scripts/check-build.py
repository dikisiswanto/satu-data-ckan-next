#!/usr/bin/env python3
"""Regression test for the generated CKAN Dockerfile overlay (no Docker needed)."""
from pathlib import Path
import importlib.util
import subprocess
import tarfile
import tempfile
import shutil
import zipfile

ROOT = Path(__file__).resolve().parents[1]
CONFIGURE = ROOT / "deploy/ckan/configure-upstream-extensions.py"
MARKER = "# Portal Satu Data CKAN extensions (generated by configure-upstream-extensions.py)"


def main() -> None:
    with tempfile.TemporaryDirectory(prefix="portal-ckan-overlay-") as tmp:
        upstream = Path(tmp)
        ckan = upstream / "ckan"
        ckan.mkdir()
        dockerfile = ckan / "Dockerfile"
        dockerfile.write_text(
            "FROM ckan/ckan-base:2.12.1\n"
            "USER root\n"
            "COPY docker-entrypoint.d/* /docker-entrypoint.d/\n"
            "RUN echo build\n"
            "USER ckan\n"
            "CMD [\"/docker-entrypoint.sh\"]\n"
        )

        for _ in range(2):
            subprocess.run(
                ["python3", str(CONFIGURE), str(ROOT), str(upstream)],
                check=True,
                capture_output=True,
                text=True,
            )

        result = dockerfile.read_text()
        assert result.count(MARKER) == 1, "generated Dockerfile block must be idempotent"
        assert result.count("COPY --chown=ckan:ckan extensions/requirements.txt") == 1
        assert result.count("RUN python -m pip install --no-cache-dir -r /tmp/portal-ckan-extensions.txt") == 1
        assert "COPY --chown=ckan:ckan install-pages.py /tmp/portal-install-pages.py" in result
        assert "COPY --chown=ckan:ckan compile-id-translations.py /tmp/portal-compile-id-translations.py" in result
        assert "&& python /tmp/portal-install-pages.py" in result
        assert "&& python /tmp/portal-compile-id-translations.py" in result
        assert 'ENV EXTRA_UWSGI_OPTS=""' in result, "runtime image must define EXTRA_UWSGI_OPTS for upstream start_ckan.sh"
        # Reproduce the upstream strict-shell expansion: unset fails, empty is valid.
        upstream_expansion = 'UWSGI_OPTS=default; if [ -n "$EXTRA_UWSGI_OPTS" ]; then UWSGI_OPTS="$UWSGI_OPTS $EXTRA_UWSGI_OPTS"; fi'
        import os
        missing_option = subprocess.run(["bash", "-uc", upstream_expansion], env={k: v for k, v in os.environ.items() if k != "EXTRA_UWSGI_OPTS"}, capture_output=True, text=True)
        assert missing_option.returncode != 0, "fixture must reproduce upstream nounset failure when EXTRA_UWSGI_OPTS is absent"
        subprocess.run(
            ["bash", "-uc", upstream_expansion],
            check=True,
            env={**os.environ, "EXTRA_UWSGI_OPTS": ""},
        )
        assert result.index('ENV EXTRA_UWSGI_OPTS=""') < result.index("USER ckan"), "uWSGI default must be part of the final runtime image"
        assert sum(line.strip() == "USER root" for line in result.splitlines()) == 2, "root must be explicit for extension install, after the fixture's initial root user"
        assert sum(line.strip() == "USER ckan" for line in result.splitlines()) == 1, "the original CKAN runtime user boundary must be preserved"
        requirements = (ckan / "extensions/requirements.txt").read_text()
        assert "ckanext-scheming==3.1.0" in requirements
        assert not any(line.strip().startswith("ckanext-pages") for line in requirements.splitlines()), "Pages must be installed by the source package-data builder"
        pages_installer = (ROOT / "deploy/ckan/install-pages.py").read_text()
        for token in ("28eba99ad85d3b9037f5aaddad1f083300c69041", "config_declaration.yaml", "migration/pages/alembic.ini", "migration/pages/script.py.mako", "migration/pages/versions/*", "importlib.import_module(\"ckanext.pages.plugin\")"):
            assert token in pages_installer, f"Pages packaging fix missing: {token}"
        # Exercise the packaging repair against a minimal source fixture without network or Docker.
        compiler_path = ROOT / "deploy/ckan/compile-id-translations.py"
        compiler_spec = importlib.util.spec_from_file_location("portal_compile_id_translations", compiler_path)
        assert compiler_spec and compiler_spec.loader
        compiler = importlib.util.module_from_spec(compiler_spec)
        compiler_spec.loader.exec_module(compiler)
        with tempfile.TemporaryDirectory(prefix="portal-ckan-i18n-check-") as locale_dir:
            catalog_path = ROOT / "deploy/ckan/theme/ckanext/wajo_theme/i18n/id/LC_MESSAGES/ckan.po"
            from babel.messages.catalog import Catalog
            from babel.messages.mofile import write_mo
            locale_root = Path(locale_dir)
            base_mo = locale_root / "id/LC_MESSAGES/ckan.mo"
            base_mo.parent.mkdir(parents=True)
            base_catalog = Catalog(locale="id", domain="ckan")
            base_catalog.add("Dashboard", "Dasbor upstream")
            base_catalog.add("Core-only label", "Label inti")
            with base_mo.open("wb") as handle:
                write_mo(handle, base_catalog)
            compiled = compiler.compile_catalog(catalog_path, locale_root)
            assert compiled.is_file() and compiled.stat().st_size > 0
            extension_output = locale_root / "wajo-theme-i18n"
            compiled_domains = compiler.compile_extension_catalogs(catalog_path, extension_output)
            assert {path.name for path in compiled_domains} == {"ckanext-dcat.mo", "ckanext-harvest.mo", "ckanext-pages.mo"}
            import gettext
            for domain, msgid, msgstr in (
                ("ckanext-harvest", "Harvest Sources", "Sumber pengambilan data"),
                ("ckanext-pages", "Add Page", "Tambah halaman"),
                ("ckanext-dcat", "Publisher name", "Nama penerbit"),
            ):
                with (extension_output / "id/LC_MESSAGES" / f"{domain}.mo").open("rb") as mo_file:
                    domain_translations = gettext.GNUTranslations(mo_file)
                assert domain_translations.gettext(msgid) == msgstr
            import gettext
            with compiled.open("rb") as mo_file:
                translated = gettext.GNUTranslations(mo_file)
            assert translated.gettext("Dashboard") == "Dasbor", "Wajo custom translations must override upstream strings"
            assert translated.gettext("Log in") == "Masuk"
            assert translated.gettext("Organizations") == "Organisasi"
            assert translated.gettext("Core-only label") == "Label inti", "upstream Indonesian strings absent from Wajo PO must be preserved"
        installer_path = ROOT / "deploy/ckan/install-pages.py"
        spec = importlib.util.spec_from_file_location("portal_install_pages", installer_path)
        assert spec and spec.loader
        installer = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(installer)
        with tempfile.TemporaryDirectory(prefix="portal-pages-package-check-") as fixture_dir:
            fixture = Path(fixture_dir)
            (fixture / "pyproject.toml").write_text(
                '[build-system]\nrequires = ["setuptools"]\nbuild-backend = "setuptools.build_meta"\n'
                '[project]\nname = "ckanext-pages"\nversion = "0.5.2"\n'
                '[tool.setuptools]\ninclude-package-data = true\n'
                '[tool.setuptools.package-data]\n"*" = ["theme/*/*.html"]\n'
                '[tool.setuptools.packages]\nfind = {}\n'
            )
            (fixture / "MANIFEST.in").write_text("recursive-include ckanext/pages/assets *\n")
            for relative in installer.REQUIRED_FILES:
                target = fixture / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text("fixture\n")
            versions = fixture / "ckanext/pages/migration/pages/versions"
            versions.mkdir(parents=True, exist_ok=True)
            (versions / "001_fixture.py").write_text('revision = "001"\n')
            installer.verify_source_assets(fixture)
            installer.patch_package_metadata(fixture)
            installer.verify_source_assets(fixture)
            import tomllib
            package_data = tomllib.loads((fixture / "pyproject.toml").read_text())["tool"]["setuptools"]["package-data"]["ckanext.pages"]
            assert set(package_data) >= {"config_declaration.yaml", "migration/pages/*", "migration/pages/versions/*"}
            manifest = (fixture / "MANIFEST.in").read_text()
            assert "include ckanext/pages/config_declaration.yaml" in manifest
            assert "recursive-include ckanext/pages/migration *" in manifest
        assert "ckanext-dcat==2.4.4" in (ckan / "extensions/requirements.txt").read_text()
        requirements_text = (ckan / "extensions/requirements.txt").read_text()
        assert "ckanext-xloader==2.6.0" in requirements_text
        assert "chardet==7.6.0" in requirements_text
        plugin_checker = (ROOT / "scripts/check-plugins.py").read_text()
        assert "ckanext.xloader.plugin" in plugin_checker
        assert "chardet.universaldetector" in plugin_checker
        assert "ckanext-geoview==0.3.2" in (ckan / "extensions/requirements.txt").read_text()
        assert "ckanext-harvest==1.6.3" in (ckan / "extensions/requirements.txt").read_text()
        assert "theme/ /tmp/portal-ckan-theme/" in result, "custom theme source must be copied into the build"
        assert "USER root\nRUN python -m pip install --no-cache-dir -r /tmp/portal-ckan-extensions.txt /tmp/portal-ckan-theme" in result
        assert "wajo_theme = ckanext.wajo_theme.plugin:WajoThemePlugin" in (ckan / "theme/setup.py").read_text()
        assert "wajo_harvest_i18n = ckanext.wajo_theme.plugin:WajoHarvestTranslationPlugin" in (ckan / "theme/setup.py").read_text()
        assert "wajo_pages_i18n = ckanext.wajo_theme.plugin:WajoPagesTranslationPlugin" in (ckan / "theme/setup.py").read_text()
        assert "wajo_dcat_i18n = ckanext.wajo_theme.plugin:WajoDcatTranslationPlugin" in (ckan / "theme/setup.py").read_text()
        assert (ckan / "theme/ckanext/wajo_theme/templates/base.html").is_file()
        assert (ckan / "theme/ckanext/wajo_theme/templates/header.html").is_file()
        assert (ckan / "theme/ckanext/wajo_theme/assets/css/wajo-theme.css").is_file()
        assert (ckan / "theme/ckanext/wajo_theme/assets/css/wajo-admin-design-system.css").is_file()
        assert (ckan / "theme/ckanext/wajo_theme/public/logo-kabupaten-wajo.webp").is_file()
        assert (ckan / "schemas/dataset.yaml").is_file()
        assert "2.12.1" in result, "generated Dockerfile should use the patch-pinned official base image"
        compose_override = (ROOT / "deploy/ckan/docker-compose.override.yml").read_text()
        ckan_service = compose_override.split("  ckan:\n", 1)[1].split("  # XLoader", 1)[0]
        assert "healthcheck:" in ckan_service, "CKAN must define an explicit healthcheck override"
        assert "- python" in ckan_service and "urllib.request.urlopen" in ckan_service, "CKAN healthcheck must use Python stdlib instead of relying on wget"
        assert "/api/action/status_show" in ckan_service and "payload.get('success') is True" in ckan_service, "CKAN healthcheck must validate status_show success"
        assert "start_period: 90s" in ckan_service and "retries: 5" in ckan_service, "CKAN healthcheck must allow startup/migration time"
        ckan_healthcheck = ckan_service.split("    healthcheck:\n", 1)[1].split("  # XLoader", 1)[0]
        assert "wget" not in ckan_healthcheck, "CKAN healthcheck must not rely on wget being installed in the base image"

        workflow = (ROOT / ".github/workflows/ci.yml").read_text()
        assert "COPY deploy/ckan/install-pages.py /tmp/install-pages.py" in workflow
        assert "COPY deploy/ckan/compile-id-translations.py /tmp/compile-id-translations.py" in workflow
        assert "&& python /tmp/compile-id-translations.py" in workflow
        assert "&& python /tmp/install-pages.py" in workflow
        assert 'ENV EXTRA_UWSGI_OPTS=""' in workflow and "RUN test \"${EXTRA_UWSGI_OPTS+x}\" = x" in workflow, "Docker smoke test must verify the uWSGI default is defined"
        init_script = ckan / "docker-entrypoint.d/50-portal-extensions.sh"
        assert init_script.is_file() and init_script.stat().st_mode & 0o111

        # Build the actual Wajo theme wheel in a temporary directory and verify
        # that every shell/dashboard asset is present in the installable artifact.
        theme_dir = ROOT / "deploy/ckan/theme"
        with tempfile.TemporaryDirectory(prefix="portal-wajo-theme-wheel-") as wheel_tmp:
            wheel_root = Path(wheel_tmp)
            subprocess.run(
                [
                    "python3", "setup.py", "bdist_wheel",
                    "--dist-dir", str(wheel_root / "dist"),
                    "--bdist-dir", str(wheel_root / "bdist"),
                    "build", "--build-base", str(wheel_root / "build"),
                ],
                cwd=theme_dir,
                check=True,
                capture_output=True,
                text=True,
            )
            wheels = list((wheel_root / "dist").glob("ckanext_wajo_theme-*.whl"))
            assert len(wheels) == 1, "Wajo theme build must produce exactly one wheel"
            with zipfile.ZipFile(wheels[0]) as wheel:
                wheel_files = set(wheel.namelist())
            required_theme_files = {
                "ckanext/wajo_theme/plugin.py",
                "ckanext/wajo_theme/templates/base.html",
                "ckanext/wajo_theme/templates/header.html",
                "ckanext/wajo_theme/templates/page.html",
                "ckanext/wajo_theme/templates/wajo_theme/dashboard.html",
                "ckanext/wajo_theme/templates/wajo_theme/data_preview.html",
                "ckanext/wajo_theme/templates/wajo_theme/icon.html",
                "ckanext/wajo_theme/templates/wajo_theme/sidebar.html",
                "ckanext/wajo_theme/assets/css/wajo-theme.css",
                "ckanext/wajo_theme/assets/css/wajo-admin-design-system.css",
                "ckanext/wajo_theme/assets/webassets.yml",
                "ckanext/wajo_theme/public/logo-kabupaten-wajo.webp",
                "ckanext/wajo_theme/i18n/id/LC_MESSAGES/ckan.po",
                "ckanext/wajo_theme/i18n/id/LC_MESSAGES/ckanext-harvest.po",
                "ckanext/wajo_theme/i18n/id/LC_MESSAGES/ckanext-pages.po",
                "ckanext/wajo_theme/i18n/id/LC_MESSAGES/ckanext-dcat.po",
            }
            missing_theme_files = required_theme_files - wheel_files
            assert not missing_theme_files, f"Wajo theme wheel is missing files: {sorted(missing_theme_files)}"

    print("CKAN Docker overlay, Wajo Admin wheel packaging, and ckanext-pages package-data fixtures passed.")


if __name__ == "__main__":
    main()
